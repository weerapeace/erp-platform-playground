-- ---------- 6) ตั้งชุดเลข pv ตามที่เจ้าของสั่ง ----------
--   หาเลขจากใบจริงในตาราง (รายวัน · ลงวันที่ย้อนหลังก็นับต่อจากเลขของวันนั้นถูก)
--   recycle_keep_column = pv_no → ใบที่ยกเลิกแต่ยังถือเลข (ใบที่ยืนยันแล้วถูกยกเลิก) ไม่คืนเลข · ยกเลิกใบร่าง = ล้างเลข (คืนเลข) ที่ API
update public.erp_numbering_rules
   set pattern = 'PV{YYYY}-{MM}-{DD}-{000}', reset_policy = 'daily',
       recycle_cancelled = true, recycle_table = 'purchase_vouchers_v2', recycle_column = 'pv_no', recycle_keep_column = 'pv_no',
       notes = 'เลขตามวันที่ใบสำคัญ วิ่งใหม่ทุกวัน · ออกตอนสร้างใบร่าง (แก้วันที่ = เลขเปลี่ยน) · ยืนยันแล้วล็อก · ยกเลิกใบร่างคืนเลข / ใบยืนยันแล้วไม่คืน (2026-11-14)',
       updated_at = now()
 where key = 'pv';
