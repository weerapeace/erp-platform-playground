import { NextResponse } from "next/server";

export const COST_PERM = "products.cost.view";   // หัวหน้า + แอดมิน (ติ๊กเพิ่มรายคนได้ในหน้าสิทธิ์)

/** คำตอบสำหรับคนไม่มีสิทธิ์ดูต้นทุน — รูปเดียวกับคำตอบปกติ (data ว่าง) หน้าจอจึงโชว์ว่างแทน error */
export function costRestricted(extra: Record<string, unknown> = {}): NextResponse {
  return NextResponse.json({ data: [], ...extra, restricted: true, error: null });
}
