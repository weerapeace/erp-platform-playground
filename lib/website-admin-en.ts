/**
 * ห่อรายการตัวเลือก (label / hint) จากไฟล์ที่แก้ไม่ได้ (เช่น ไฟล์มิเรอร์หน้าร้าน) ให้อ่านแล้วได้อังกฤษตอนเลือก EN
 * ป้ายเป็น getter → อ่านตอน render ทุกครั้ง (ประกาศระดับไฟล์ได้) · ค่า/คีย์อื่นเหมือนเดิมทุกอย่าง
 */
export function localizedOpts<T extends { label: string; hint?: string }>(list: readonly T[]): T[] {
  return list.map((o) => {
    const c = { ...o };
    Object.defineProperty(c, "label", { get: () => labelEn(o.label), enumerable: true });
    if (typeof o.hint === "string") Object.defineProperty(c, "hint", { get: () => labelEn(o.hint as string), enumerable: true });
    return c;
  });
}

export function labelEn(th: string): string {
  if (!th) return th;
  return tr(th, EN[th] ?? th);
}
