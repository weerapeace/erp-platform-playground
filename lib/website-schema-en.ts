const TH = /[฀-๿]/;

function lookup(th: string): string | undefined {
  const hit = EN[th] ?? EN_PATTERNS[th];
  if (hit !== undefined) return hit;
  const nums = th.match(/\d+/g);
  if (nums) {
    const pat = EN_PATTERNS[th.replace(/\d+/g, "#")];
    if (pat !== undefined) {
      let i = 0;
      return pat.replace(/#/g, () => nums[i++] ?? "#");
    }
  }
  const req = /^ยังไม่ได้กรอก "(.+)"$/.exec(th);
  if (req) return `"${lookup(req[1]) ?? req[1]}" is not filled in yet`;
  return undefined;
}

function translate(th: string): string {
  const hit = lookup(th);
  if (hit !== undefined) return hit;
  // "หัว: ท้าย" → แปลทีละส่วน (ส่วนที่ไม่รู้จัก เช่น ชื่อที่ผู้ใช้ตั้ง = คงเดิม)
  const cut = th.indexOf(": ");
  if (cut > 0) {
    const head = th.slice(0, cut);
    const tail = th.slice(cut + 2);
    const h = lookup(head) ?? head;
    const t = lookup(tail) ?? translate(tail);
    if (h !== head || t !== tail) return `${h}: ${t}`;
  }
  return th;
}

/** ป้ายไทยจาก schema → อังกฤษเมื่อเลือก EN (ไม่รู้จัก = ไทยเดิม) */
export function labelEn(th: string): string;
export function labelEn(th: string | undefined): string | undefined;
export function labelEn(th: string | undefined): string | undefined {
  if (!th || getLang() !== "en" || !TH.test(th)) return th;
  return translate(th);
}

