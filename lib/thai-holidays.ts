/**
 * วันหยุดราชการไทย (ของกลาง — ปฏิทินกลาง ScheduleBoard โชว์ในช่องวัน)
 *   - วันหยุดวันที่ตายตัว: คิดให้ทุกปีอัตโนมัติ
 *   - วันหยุดตามจันทรคติ (มาฆะ/วิสาขะ/อาสาฬหะ/เข้าพรรษา) เปลี่ยนทุกปี → ใส่ใน LUNAR ทีละปี (ปีที่ยังไม่ใส่ = ไม่โชว์)
 *   - ไม่รวมวันหยุดชดเชย / วันหยุดพิเศษที่ ครม. ประกาศเพิ่ม · วันหยุดบริษัทจริงใช้ตารางเงินเดือน (payroll_holidays)
 */
const FIXED: [string, string][] = [
  ["01-01", "วันขึ้นปีใหม่"],
  ["04-06", "วันจักรี"],
  ["04-13", "วันสงกรานต์"], ["04-14", "วันสงกรานต์"], ["04-15", "วันสงกรานต์"],
  ["05-01", "วันแรงงาน"],
  ["05-04", "วันฉัตรมงคล"],
  ["06-03", "วันเฉลิมฯ พระราชินี"],
  ["07-28", "วันเฉลิมฯ ร.10"],
  ["08-12", "วันแม่แห่งชาติ"],
  ["10-13", "วันนวมินทรมหาราช"],
  ["10-23", "วันปิยมหาราช"],
  ["12-05", "วันพ่อแห่งชาติ"],
  ["12-10", "วันรัฐธรรมนูญ"],
  ["12-31", "วันสิ้นปี"],
];

const LUNAR: Record<number, [string, string][]> = {
  2026: [["03-03", "วันมาฆบูชา"], ["05-31", "วันวิสาขบูชา"], ["07-29", "วันอาสาฬหบูชา"], ["07-30", "วันเข้าพรรษา"]],
};

/** "YYYY-MM-DD" → ชื่อวันหยุด ของปีที่ขอ */
export function thaiHolidays(year: number): Record<string, string> {
  const out: Record<string, string> = {};
  for (const [md, name] of [...FIXED, ...(LUNAR[year] ?? [])]) out[`${year}-${md}`] = name;
  return out;
}

/** ชื่อวันหยุดของวันนั้น (ไม่ใช่วันหยุด = undefined) */
export function thaiHolidayOf(ymd: string): string | undefined {
  return thaiHolidays(Number(ymd.slice(0, 4)))[ymd];
}
